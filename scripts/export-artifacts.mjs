#!/usr/bin/env node
// Turns the Foundry build into what the app needs:
//   lib/abi.ts                  ABIs and the deterministic contract addresses (client-safe)
//   lib/server/initcode.json    creation code the server deploys through CREATE2
//
// Addresses come from Arc's CREATE2 factory, the fixed salt below and the exact
// creation code, so they are known before anything is deployed and are the same
// on any chain with the factory and USDC at the same address.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { concatHex, encodeAbiParameters, getContractAddress, keccak256, toHex } from "viem";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const FACTORY = "0x4e59b44847b379578588920cA78FbF26c0B4956C";
const USDC = "0x3600000000000000000000000000000000000000";
const SALT = keccak256(toHex("accrue.arc.v1"));

function artifact(name) {
  const path = join(root, "contracts", "out", `${name}.sol`, `${name}.json`);
  const json = JSON.parse(readFileSync(path, "utf8"));
  return { abi: json.abi, bytecode: json.bytecode.object };
}

const jobs = artifact("AccrueJobs");
const panel = artifact("AccruePanel");

const jobsInit = concatHex([jobs.bytecode, encodeAbiParameters([{ type: "address" }], [USDC])]);
const jobsAddress = getContractAddress({ opcode: "CREATE2", from: FACTORY, salt: SALT, bytecode: jobsInit });
const panelInit = concatHex([panel.bytecode, encodeAbiParameters([{ type: "address" }], [jobsAddress])]);
const panelAddress = getContractAddress({ opcode: "CREATE2", from: FACTORY, salt: SALT, bytecode: panelInit });

const banner = "// Generated by scripts/export-artifacts.mjs from the Foundry build. Do not edit.\n";
const abiFile =
  banner +
  `export const CREATE2_FACTORY = "${FACTORY}" as const;\n` +
  `export const DEPLOY_SALT = "${SALT}" as const;\n` +
  `export const JOBS_ADDRESS = "${jobsAddress}" as const;\n` +
  `export const PANEL_ADDRESS = "${panelAddress}" as const;\n\n` +
  `export const jobsAbi = ${JSON.stringify(jobs.abi, null, 2)} as const;\n\n` +
  `export const panelAbi = ${JSON.stringify(panel.abi, null, 2)} as const;\n`;

writeFileSync(join(root, "lib", "abi.ts"), abiFile);
mkdirSync(join(root, "lib", "server"), { recursive: true });
writeFileSync(
  join(root, "lib", "server", "initcode.json"),
  JSON.stringify(
    {
      factory: FACTORY,
      salt: SALT,
      jobs: { address: jobsAddress, initCode: jobsInit, initCodeHash: keccak256(jobsInit) },
      panel: { address: panelAddress, initCode: panelInit, initCodeHash: keccak256(panelInit) },
    },
    null,
    2,
  ) + "\n",
);

console.log(`AccrueJobs  ${jobsAddress}`);
console.log(`AccruePanel ${panelAddress}`);
